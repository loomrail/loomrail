export type Locale = "en" | "ru";
export type TranslationKey = keyof typeof en;
export type Translator = (
  key: TranslationKey,
  parameters?: Readonly<Record<string, string | number>>,
) => string;

const messages: Record<Locale, Record<TranslationKey, string>> = { en, ru };

export const isLocale = (value: unknown): value is Locale => value === "en" || value === "ru";

export const readLocale = (): Locale => {
  const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  if (isLocale(stored)) return stored;
  return window.navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
};

export const applyLocale = (locale: Locale): void => {
  window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  document.documentElement.lang = locale;
};

export const translate = (
  locale: Locale,
  key: TranslationKey,
  parameters: Readonly<Record<string, string | number>> = {},
): string =>
  Object.entries(parameters).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translator;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider = ({ children }: { children: ReactNode }): React.JSX.Element => {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const initialLocale = readLocale();
    applyLocale(initialLocale);
    return initialLocale;
  });
  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale: (nextLocale) => {
        applyLocale(nextLocale);
        setLocaleState(nextLocale);
      },
      t: (key, parameters) => translate(locale, key, parameters),
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = (): I18nContextValue => {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be rendered inside I18nProvider");
  return value;
};
